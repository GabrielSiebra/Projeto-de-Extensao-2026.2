import type { Reservation } from "../types";
import { addDaysISO, currentHour, hourLabel, toISODate } from "../lib/format";

const today = toISODate(new Date());
const hour = Math.min(Math.max(currentHour(), 8), 21);

function make(
  seq: number,
  overrides: Partial<Reservation> & Pick<Reservation, "venueId" | "date" | "time">,
): Reservation {
  const field = overrides.fieldName ?? "Campo 01";
  const amount = overrides.amount ?? 140;
  const fees = overrides.fees ?? Math.round(amount * 0.05);
  return {
    id: `res-${seq}`,
    code: `MC-${String(4820 + seq)}`,
    fieldId: `${overrides.venueId}-campo-1`,
    fieldName: field,
    durationHours: 1,
    accountType: "individual",
    clientName: "Rafael Mendonça",
    amount,
    fees,
    total: amount + fees,
    status: "confirmed",
    createdAt: addDaysISO(-3),
    ...overrides,
  };
}

